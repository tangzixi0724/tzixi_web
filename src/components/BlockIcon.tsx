/** 把一种字符的连续块合并成 path，减少节点数 */
function toPath(rows: string[], ink: string, scale: number): string {
  const parts: string[] = [];
  rows.forEach((row, y) => {
    let runStart = -1;
    for (let x = 0; x <= 16; x += 1) {
      const filled = row[x] === ink;
      if (filled && runStart === -1) runStart = x;
      if (!filled && runStart !== -1) {
        parts.push(
          `M${runStart * scale} ${y * scale}h${(x - runStart) * scale}v${scale}h-${(x - runStart) * scale}z`,
        );
        runStart = -1;
      }
    }
  });
  return parts.join('');
}

export function BlockIcon({ name, size = 32, image, alt = '' }: IconProps) {
  // jar 里带了真实图标就用真实的，像素图要硬边放大
  if (image) {
    return (
      <img
        src={image}
        width={size}
        height={size}
        alt={alt}
        className="block-icon block-icon--image"
        loading="lazy"
        decoding="async"
      />
    );
  }

  const rows = GRIDS[name] ?? [];
  return (
    <svg
      viewBox="0 0 16 16"
      width={size}
      height={size}
      aria-hidden="true"
      focusable="false"
      shapeRendering="crispEdges"
      className="block-icon"
    >
      <path d={toPath(rows, '#', 1)} />
      <path d={toPath(rows, 'X', 1)} className="block-icon__shade" />
    </svg>
  );
}
